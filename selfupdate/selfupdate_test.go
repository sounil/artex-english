func TestValidateRepo(t *testing.T) {
	good := map[string]string{
		"sounil/artex-english":    "sounil/artex-english",
		" owner/repo.name_2 ":     "owner/repo.name_2",
		"jiwoochris/artex-global": "jiwoochris/artex-global",
	}
	for in, want := range good {
		got, err := ValidateRepo(in)
		if err != nil || got != want {
			t.Errorf("ValidateRepo(%q) = %q, %v; want %q", in, got, err, want)
		}
	}
	for _, bad := range []string{
		"", "no-slash", "a/b/c", "owner/", "/repo", "-owner/repo", "owner/re po",
		"owner/../../evil", "owner/..", "owner/.", "owner/repo?x=1", "owner/repo#x", "https://github.com/o/r",
	} {
		if got, err := ValidateRepo(bad); err == nil {
			t.Errorf("ValidateRepo(%q) = %q; want an error", bad, got)
		}
	}
}

// Settings beats the environment, which beats the default; an invalid value at the level that
// applies is an error, never a fallback to a lower level.
func TestResolveRepoPrecedence(t *testing.T) {
	cases := []struct {
		name, setting, env, wantRepo, wantSource string
		wantErr                                  bool
	}{
		{name: "default", wantRepo: DefaultRepo, wantSource: RepoFromDefault},
		{name: "env", env: "someone/fork", wantRepo: "someone/fork", wantSource: RepoFromEnv},
		{name: "settings beats env", setting: "ui/choice", env: "someone/fork", wantRepo: "ui/choice", wantSource: RepoFromSettings},
		{name: "blank setting falls through", setting: "   ", env: "someone/fork", wantRepo: "someone/fork", wantSource: RepoFromEnv},
		{name: "invalid setting is an error", setting: "bad value", env: "someone/fork", wantSource: RepoFromSettings, wantErr: true},
		{name: "invalid env is an error", env: "bad value", wantSource: RepoFromEnv, wantErr: true},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			t.Setenv(RepoEnv, tc.env)
			repo, source, err := ResolveRepo(tc.setting)
			if (err != nil) != tc.wantErr || repo != tc.wantRepo || source != tc.wantSource {
				t.Fatalf("ResolveRepo(%q) with env %q = %q, %q, %v", tc.setting, tc.env, repo, source, err)
			}
		})
	}
	if got := latestURL("someone/fork"); got != "https://api.github.com/repos/someone/fork/releases/latest" {
		t.Fatalf("latestURL = %q", got)
	}
	if _, err := FetchLatest(t.Context(), nil, "bad value"); err == nil {
		t.Fatal("FetchLatest must refuse an invalid source before any request")
	}
}
